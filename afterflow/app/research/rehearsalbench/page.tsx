import type { Metadata } from "next";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { SiteHeader } from "@/components/site-header";
import { SiteFooter } from "@/components/site-footer";
import { RehearsalBench } from "@/components/rehearsal-bench";
import { rehearsalBench, rehearsalBenchSocialImage } from "@/content/research";
import { absoluteUrl, serializeJsonLd, siteConfig } from "@/lib/site";
import "../rehearsalbench.css";

const title = rehearsalBench.title;
const url = rehearsalBench.href;
export const metadata: Metadata = {
  title, description: rehearsalBench.description,
  alternates: { canonical: url },
  openGraph: {
    type: "article", siteName: siteConfig.name, title: `${title} — Afterflow`,
    description: rehearsalBench.description, url,
    publishedTime: rehearsalBench.publishedIso, images: [rehearsalBenchSocialImage],
  },
  twitter: { card: "summary_large_image", title: `${title} — Afterflow`, description: rehearsalBench.description, images: [rehearsalBenchSocialImage] },
};

export default function RehearsalBenchPage() {
  // Generated by `pnpm build:rehearsalbench` from content/rehearsalbench/template.html.
  const html = readFileSync(resolve("content/rehearsalbench/page.html"), "utf8");
  const articleUrl = absoluteUrl(rehearsalBench.href);
  const article = {
    "@context": "https://schema.org", "@type": "BlogPosting", "@id": `${articleUrl}#article`,
    url: articleUrl, headline: rehearsalBench.title,
    description: rehearsalBench.description, datePublished: rehearsalBench.publishedIso,
    image: absoluteUrl(rehearsalBenchSocialImage.url),
    inLanguage: "en", author: { "@id": absoluteUrl("/#organization") },
    publisher: { "@id": absoluteUrl("/#organization") },
    mainEntityOfPage: { "@type": "WebPage", "@id": articleUrl },
    isPartOf: { "@id": absoluteUrl("/#website") },
    isBasedOn: rehearsalBench.repoHref,
  };
  return (
    <>
      <a className="skip-link" href="#main">Skip to content</a>
      <SiteHeader />
      <script type="application/ld+json" dangerouslySetInnerHTML={{ __html: serializeJsonLd(article) }} />
      <RehearsalBench html={html} />
      <SiteFooter topHref="#main" />
    </>
  );
}
